import { test } from 'node:test';
import assert from 'node:assert/strict';
import { webcrypto, randomBytes } from 'node:crypto';
import { createApp } from '../server/index.js';
import { Vault } from '../server/vault.js';

const payload = () => ({ ciphertext: randomBytes(40).toString('base64'), iv: randomBytes(12).toString('base64'), access: randomBytes(32).toString('hex') });
test('access and owner capabilities are independent; expiry is enforced server-side', () => {
  let clock = 1000;
  const vault = new Vault({ now: () => clock });
  const data = payload();
  const item = vault.create(data);
  assert.equal(item.expiresAt, 301000);
  assert.equal(vault.read(item.id, item.owner), null);
  assert.equal(vault.read(item.id, 'wrong'), null);
  assert.equal(vault.revoke(item.id, data.access), false);
  assert.equal(vault.read(item.id, data.access).ciphertext, data.ciphertext);
  clock = item.expiresAt;
  assert.equal(vault.read(item.id, data.access), null);
  assert.equal(vault.messages.size, 0);
});
test('revoke removes the original immediately', () => {
  const vault = new Vault();
  const data = payload();
  const item = vault.create(data);
  assert.equal(vault.revoke(item.id, item.owner), true);
  assert.equal(vault.read(item.id, data.access), null);
});
test('API encrypted round trip, malformed requests, origin isolation and revocation', async t => {
  let clock = Date.now();
  const server = createApp({ now: () => clock, apiKey: '' });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (path, body, method = 'POST', headers = {}) => fetch(base + path, { method, headers: { 'Content-Type': 'application/json', ...headers }, body: JSON.stringify(body) });
  const original = 'bro these numbers are wrong 😭';
  const key = await webcrypto.subtle.generateKey({ name: 'AES-GCM', length: 256 }, true, ['encrypt', 'decrypt']);
  const iv = randomBytes(12);
  const ciphertext = Buffer.from(await webcrypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, new TextEncoder().encode(original))).toString('base64');
  const access = randomBytes(32).toString('hex');
  const response = await request('/api/messages', { ciphertext, iv: iv.toString('base64'), access });
  assert.equal(response.status, 201);
  const item = await response.json();
  const opened = await (await request(`/api/messages/${item.id}/open`, { access })).json();
  assert.equal('owner' in opened, false);
  assert.equal('access' in opened, false);
  assert.equal('key' in opened, false);
  const decrypted = await webcrypto.subtle.decrypt({ name: 'AES-GCM', iv }, key, Buffer.from(opened.ciphertext, 'base64'));
  assert.equal(new TextDecoder().decode(decrypted), original);
  const wrongKey = await webcrypto.subtle.generateKey({ name: 'AES-GCM', length: 256 }, true, ['decrypt']);
  await assert.rejects(webcrypto.subtle.decrypt({ name: 'AES-GCM', iv }, wrongKey, Buffer.from(opened.ciphertext, 'base64')));
  assert.equal((await request(`/api/messages/${item.id}/open`, { access: 'wrong' })).status, 404);
  assert.equal((await request('/api/messages', payload(), 'POST', { Origin: 'https://evil.example' })).status, 403);
  assert.equal((await request('/api/messages', null)).status, 400);
  assert.equal((await request('/api/messages', { ciphertext: '<script>' })).status, 400);
  assert.equal((await request('/api/rewrite', { text: original })).status, 503);
  assert.equal((await fetch(base + '/app.js')).status, 200);
  assert.equal((await fetch(base + '/index.html')).status, 200);
  assert.equal((await fetch(base + '/.env')).status, 404);
  assert.equal((await request(`/api/messages/${item.id}`, { owner: access }, 'DELETE')).status, 404);
  assert.equal((await request(`/api/messages/${item.id}`, { owner: item.owner }, 'DELETE')).status, 200);
  assert.equal((await request(`/api/messages/${item.id}/open`, { access })).status, 404);
  const expiring = await (await request('/api/messages', { ciphertext, iv: iv.toString('base64'), access })).json();
  clock = expiring.expiresAt;
  assert.equal((await request(`/api/messages/${expiring.id}/open`, { access })).status, 404);
});
